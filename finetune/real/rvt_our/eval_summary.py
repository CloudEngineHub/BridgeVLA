#!/usr/bin/env python3
"""Episode tally for the real-robot eval runs of one checkpoint.

Real-robot eval is one-episode-per-process: ``eval_client.py``
runs a single episode, the operator ends it with **[s]**/**[f]**, and the run
folder is stamped ``…_success`` / ``…_fail``. This module turns that pile of
folders into a count — how many episodes were run, which passed, which failed —
so nobody has to keep the tally by hand.

Everything is derived by **scanning the run folders**. There is no counter held
in the inference server (which the operator restarts between episodes, so an
in-memory counter would reset to zero every time) and no append-only log that
could drift out of sync with what is actually on disk. Delete a bad episode's
folder and it leaves the tally; nothing else needs fixing.

Layout scanned (see ``eval_flask_app.py`` for who writes what)::

    <dir of the .pth>/eval/<model_stem>/
        summary_by_variation.txt                 <- roll-up across all 7 (below)
        basic/                                   <- pass THIS dir as the root
            summary.txt                          <- regenerated by write_summary()
            episodes.csv                         <- one row per episode
            ep001_0718_190656_<instruction_slug>_success/
                episode_meta.txt  variation / checkpoint / instruction / times /
                                  steps / result
                step_0000/ …      one folder per predicted keypose
            ep002_0718_192210_<instruction_slug>_fail/
        height/  distractor/  combination/  category/  lighting/  background/

The variation is the generalization axis being tested (:data:`VARIATIONS`),
declared in the eval client and sent to the server on POST /reset. Episodes are
numbered **per variation**, so ``basic`` and ``lighting`` each start at ep001 and
carry their own success rate — which is the comparison the whole split exists to
make.

Older layouts still scan: run folders sitting directly under ``<model_stem>/``
(before the variation level) group as "(no variation)", and folders predating the
``epNNN_`` prefix (``0718_190656_<slug>_success``) list with ``#`` = ``-``.

Episode numbers are allocated as ``max(existing) + 1``, so deleting the middle
of a campaign never renumbers or reuses; only deleting the most recent episode
hands its number to the next one.

Usage::

    python eval_summary.py <ckpt dir>/eval/model_1500   # default: by task ×
                                                        # Basic/Distractor/
                                                        # Background/height
    python eval_summary.py <ckpt dir>/eval              # every model under it
    python eval_summary.py <dir> --print-only           # don't write files
    python eval_summary.py <dir> --full                 # old full roll-up
                                                        # (all folders + per-
                                                        # variation summary.txt)

Stdlib only — imported by the Flask server AND the eval client, neither of which
should gain dependencies through it.
"""

from __future__ import annotations

import argparse
import csv
import datetime
import glob
import os
import re
import sys
import textwrap

# ---- layout contract with eval_flask_app.py (keep the two in sync) ----------
RESULTS       = ("success", "fail", "aborted")
SCORED        = ("success", "fail")   # what enters the success-rate denominator
EP_PREFIX_FMT = "ep{:03d}"
EPISODE_META  = "episode_meta.txt"
SUMMARY_TXT   = "summary.txt"
EPISODES_CSV  = "episodes.csv"
ROLLUP_TXT    = "summary_by_variation.txt"
STEP_GLOB     = "step_*"

# The standard generalization axes a real-robot campaign is split across; each
# becomes a sub-folder of <model_stem>/ holding its own episodes and its own
# success rate. Declared in the eval client (EVAL_VARIATION) and sent to the
# server on /reset.
#
# NOT a closed set: the variation is free text now (fill-in-the-blank), so a
# custom name like "test" / "test1" is accepted and gets its own bucket. These
# are just the well-known axes — they seed the roll-up's row order and let
# is_model_dir() recognize a campaign dir cheaply. validate_variation() only
# rejects a name that would break the folder path, not an unfamiliar one.
VARIATIONS = ("basic", "height", "distractor", "combination",
              "category", "lighting", "background")
# The core axes we care about for a post-hoc headline rate. Exact folder names
# only — ``basic_test`` / ``distractor_retry`` / … are deliberately excluded.
# Display order matches the usual campaign write-up (Basic → Distractor →
# Background → height → lighting); folder names on disk stay lowercase.
CORE_VARIATIONS = ("basic", "distractor", "background", "height", "lighting")
CORE_LABELS = {
    "basic": "Basic",
    "distractor": "Distractor",
    "background": "Background",
    "height": "height",
    "lighting": "lighting",
}
CORE_ROLLUP_TXT = "summary_core_by_task.txt"
NO_VARIATION = "(no variation)"   # display name for pre-split / unlabelled runs

# ``[ep<idx>_]<mmdd_HHMMSS>[_<slug>][_<result>]`` — the stamp is the anchor, so
# a stray folder (a stashed copy, a notes dir) is simply not a run.
_RUN_RE = re.compile(r"^(?:ep(?P<idx>\d+)_)?(?P<stamp>\d{4}_\d{6})(?P<rest>.*)$")
_META_TIME_FMT = "%Y-%m-%d %H:%M:%S"


# Variations
# A variation becomes a single sub-folder under <model_stem>/, so the only names
# we must refuse are the ones that would break or escape that path.
_BAD_VARIATION = re.compile(r"[/\\]")


def validate_variation(variation: str) -> str:
    """Return *variation* if it is a usable folder name, else raise.

    The variation is free text (fill-in-the-blank, not a fixed menu): any
    non-empty name that is a single safe path component is accepted and becomes
    the sub-folder ``<model_stem>/<variation>/`` with its own episode numbering
    and success rate. :data:`VARIATIONS` lists the well-known axes, but a custom
    name like ``test`` / ``test1`` is fine. Validation only guards the layout —
    an empty string, a path separator, or ``.`` / ``..`` is rejected so a bad
    name lands in its own bucket instead of corrupting the tree.

    Called at client import (so a bad name fails in a second, before the camera
    and arm come up) and again on the server's /reset (so a stale client cannot
    write into an unusable path).
    """
    v = str(variation or "").strip()
    if not v or v in (".", "..") or _BAD_VARIATION.search(v):
        raise ValueError(
            f"invalid eval variation {variation!r}; use a non-empty folder "
            f"name without '/' or '\\' (a standard axis like "
            f"{', '.join(VARIATIONS)}, or a custom name like 'test')"
        )
    return v


# Run-folder naming
def format_run_name(index: int, stamp: str, slug: str = "") -> str:
    """Mint a run-folder name: ``ep007_0718_190656_<slug>``.

    The result suffix is appended later, by POST /finish.
    """
    parts = [EP_PREFIX_FMT.format(index), stamp]
    if slug:
        parts.append(slug)
    return "_".join(parts)


def parse_run_name(name: str):
    """``ep007_0718_190656_swap-eggplants_success`` → dict, or None if not a run."""
    m = _RUN_RE.match(name)
    if not m:
        return None
    rest, result = m.group("rest"), None
    for r in RESULTS:
        if rest.endswith("_" + r):
            rest, result = rest[: -len(r) - 1], r
            break
    idx = m.group("idx")
    return {
        "index":  int(idx) if idx is not None else None,
        "stamp":  m.group("stamp"),
        "slug":   rest.lstrip("_"),
        "result": result,          # None => episode never finished
    }


def next_episode_index(root: str) -> int:
    """Episode number for the next run under *root* (1-based, max + 1)."""
    top = 0
    try:
        names = os.listdir(root)
    except OSError:
        return 1
    for name in names:
        parsed = parse_run_name(name)
        if parsed and parsed["index"] and os.path.isdir(os.path.join(root, name)):
            top = max(top, parsed["index"])
    return top + 1


# Scanning
def _read_meta(path: str) -> dict:
    """Parse ``episode_meta.txt``'s ``key: value`` lines (first key wins)."""
    meta = {}
    try:
        with open(path) as f:
            for line in f:
                if ":" in line:
                    k, v = line.split(":", 1)
                    meta.setdefault(k.strip(), v.strip())
    except OSError:
        pass
    return meta


def _count_steps(run_dir: str) -> int:
    return sum(1 for d in glob.glob(os.path.join(run_dir, STEP_GLOB))
               if os.path.isdir(d))


def _parse_time(text: str):
    try:
        return datetime.datetime.strptime(text, _META_TIME_FMT)
    except (ValueError, TypeError):
        return None


def scan_episodes(root: str) -> list:
    """Every eval run directly under *root*, oldest first.

    Each record: index, folder, instruction, result, steps, start/end, seconds,
    checkpoint. ``result`` is None for a run that never reached POST /finish
    (server killed mid-episode, client crashed) — those are reported separately
    and kept out of the success rate rather than silently scored as failures.
    """
    episodes = []
    try:
        names = sorted(os.listdir(root))
    except OSError:
        return episodes

    for name in names:
        run_dir = os.path.join(root, name)
        parsed = parse_run_name(name)
        if not parsed or not os.path.isdir(run_dir):
            continue
        meta = _read_meta(os.path.join(run_dir, EPISODE_META))

        steps = meta.get("steps", "")
        steps = int(steps) if steps.isdigit() else _count_steps(run_dir)

        t0, t1 = _parse_time(meta.get("start_time")), _parse_time(meta.get("end_time"))
        seconds = int((t1 - t0).total_seconds()) if t0 and t1 else None

        # Folder name is authoritative for the result: renaming it is the act
        # that closes an episode, and it is what the operator sees in `ls`.
        # Folder placement is authoritative for the variation too (it is what
        # the tally groups by); episode_meta.txt only fills in for a run whose
        # parent dir was renamed by hand.
        parent = os.path.basename(os.path.abspath(root).rstrip(os.sep))
        variation = parent if parent in VARIATIONS else meta.get("variation", "")

        episodes.append({
            "index":       parsed["index"],
            "folder":      name,
            "path":        run_dir,
            "variation":   variation,
            "stamp":       parsed["stamp"],
            "instruction": (meta.get("instruction") or parsed["slug"]
                            or "(no instruction)"),
            "result":      parsed["result"] or meta.get("result") or None,
            "steps":       steps,
            "start_time":  meta.get("start_time", ""),
            "end_time":    meta.get("end_time", ""),
            "seconds":     seconds,
            "checkpoint":  meta.get("checkpoint", ""),
        })

    episodes.sort(key=lambda e: (e["stamp"], e["index"] or 0))
    return episodes


def find_roots(path: str) -> list:
    """Directories under *path* that hold eval runs (``path`` itself included).

    Lets the CLI take a single ``eval/<model_stem>/``, a whole ``eval/`` folder,
    or a checkpoint dir and do the right thing. ``step_*`` and run folders are
    pruned from the walk so the scan stays shallow.
    """
    roots = []
    for dirpath, dirnames, _ in os.walk(path):
        runs = [d for d in dirnames if parse_run_name(d)]
        if runs:
            roots.append(dirpath)
        dirnames[:] = [d for d in dirnames
                       if d not in runs and not d.startswith("step_")]
    return sorted(roots)


def tally(episodes: list) -> dict:
    """Overall counts + per-instruction breakdown."""
    scored = [e for e in episodes if e["result"] in SCORED]
    n_succ = sum(1 for e in scored if e["result"] == "success")

    per_task = {}
    for e in episodes:
        t = per_task.setdefault(
            e["instruction"],
            {"instruction": e["instruction"], "success": 0, "fail": 0,
             "aborted": 0, "unfinished": 0},
        )
        t[e["result"] or "unfinished"] += 1
    for t in per_task.values():
        t["scored"] = t["success"] + t["fail"]
        t["success_rate"] = (t["success"] / t["scored"]) if t["scored"] else None

    return {
        "total":        len(episodes),
        "scored":       len(scored),
        "success":      n_succ,
        "fail":         len(scored) - n_succ,
        "aborted":      sum(1 for e in episodes if e["result"] == "aborted"),
        "unfinished":   sum(1 for e in episodes if e["result"] is None),
        "success_rate": (n_succ / len(scored)) if scored else None,
        "per_task":     list(per_task.values()),
    }


def _pct(rate) -> str:
    return "  n/a " if rate is None else f"{rate * 100:5.1f}%"


def _fmt_duration(seconds) -> str:
    if seconds is None:
        return "-"
    m, s = divmod(max(int(seconds), 0), 60)
    h, m = divmod(m, 60)
    if h:
        return f"{h}h{m:02d}m"
    return f"{m}m{s:02d}s" if m else f"{s}s"


def _ep_tag(ep: dict) -> str:
    """``ep007`` — or the bare timestamp for a pre-``epNNN`` legacy folder."""
    return f"ep{ep['index']:03d}" if ep["index"] else ep["stamp"]


def _fmt_start(ep: dict) -> str:
    if ep["start_time"]:
        return ep["start_time"][5:]           # drop the year: "07-18 19:06:56"
    s = ep["stamp"]                           # fall back to the folder stamp
    return f"{s[0:2]}-{s[2:4]} {s[5:7]}:{s[7:9]}:{s[9:11]}"


def format_summary(episodes: list, root: str = "", checkpoint: str = "") -> str:
    """Human-readable tally — written to summary.txt and printed on /finish."""
    st = tally(episodes)
    ckpt = checkpoint or next((e["checkpoint"] for e in reversed(episodes)
                               if e["checkpoint"]), "")
    out = ["=" * 78, "Real-robot eval summary", "=" * 78]
    if ckpt:
        out.append(f"checkpoint : {ckpt}")
    if root:
        out.append(f"log dir    : {root}")
        # The folder this summary sits in IS the variation, so read it off the
        # path rather than threading it through every caller. A custom (free-text)
        # variation is not in VARIATIONS, so fall back to the scanned episodes'
        # recorded variation; skip the line only for the pre-split model dir.
        base = os.path.basename(os.path.abspath(root).rstrip(os.sep))
        var = base if base in VARIATIONS else next(
            (e["variation"] for e in episodes if e.get("variation")), "")
        if var:
            out.append(f"variation  : {var}")
    out.append(f"generated  : {datetime.datetime.now().strftime(_META_TIME_FMT)}")
    out.append("")

    if not episodes:
        out += ["no eval runs found yet.", "=" * 78]
        return "\n".join(out)

    out.append(f"episodes scored : {st['scored']:3d}   "
               f"success {st['success']}  /  fail {st['fail']}   "
               f"→  success rate {_pct(st['success_rate'])}")
    if st["aborted"] or st["unfinished"]:
        # Not counted either way: an abort is an operator/hardware do-over, and
        # an unfinished run never got a verdict. Scoring them as failures would
        # quietly deflate the rate.
        out.append(f"not counted     : {st['aborted']:3d} aborted, "
                   f"{st['unfinished']} unfinished (excluded from the rate)")
    out.append("")

    # ---- which episodes landed where ----
    # The question this file exists to answer at a glance: which numbers passed
    # and which failed. The per-episode table below has the same information,
    # but not in a form you can read off in one line.
    by_result = {}
    for e in episodes:
        by_result.setdefault(e["result"] or "unfinished", []).append(e)
    out.append("-- by result " + "-" * 64)
    for key in ("success", "fail", "aborted", "unfinished"):
        if key in by_result:
            tags = ", ".join(_ep_tag(e) for e in by_result[key])
            out.append(textwrap.fill(
                f"{key:<10} ({len(by_result[key]):2d}): {tags}",
                width=78, subsequent_indent=" " * 17))
    out.append("")

    # ---- per instruction ----
    out += ["-- by instruction " + "-" * 60,
            " rate    n   succ  fail  other  instruction"]
    for t in st["per_task"]:
        other = t["aborted"] + t["unfinished"]
        out.append(f"{_pct(t['success_rate'])} {t['scored']:4d}  "
                   f"{t['success']:4d}  {t['fail']:4d}  {other:5d}  "
                   f"{t['instruction']}")
    out.append("")

    # ---- per episode ----
    out += ["-- episodes " + "-" * 66,
            "  #  result      steps  start           dur      instruction"]
    for e in episodes:
        idx = f"{e['index']:03d}" if e["index"] else " - "
        instr = e["instruction"]
        instr = instr if len(instr) <= 46 else instr[:45] + "…"
        out.append(f"{idx}  {(e['result'] or 'unfinished'):<10} "
                   f"{e['steps']:5d}  {_fmt_start(e):<15} "
                   f"{_fmt_duration(e['seconds']):<8} {instr}")
    out.append("=" * 78)
    return "\n".join(out)


# Writing
_CSV_FIELDS = ["index", "variation", "folder", "instruction", "result", "steps",
               "start_time", "end_time", "seconds", "checkpoint"]


def write_summary(root: str, episodes: list = None, checkpoint: str = "") -> dict:
    """Regenerate ``summary.txt`` + ``episodes.csv`` under *root* from a scan.

    Both files are rewritten from scratch every time, so they can never drift
    from the folders on disk. Returns the :func:`tally` dict.
    """
    if episodes is None:
        episodes = scan_episodes(root)

    with open(os.path.join(root, SUMMARY_TXT), "w") as f:
        f.write(format_summary(episodes, root=root, checkpoint=checkpoint) + "\n")

    with open(os.path.join(root, EPISODES_CSV), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=_CSV_FIELDS, extrasaction="ignore")
        w.writeheader()
        for e in episodes:
            w.writerow(e)

    return tally(episodes)


# Roll-up across variations
def is_model_dir(path: str) -> bool:
    """True if *path* is a ``<model_stem>/`` — i.e. it holds variation sub-folders.

    Recognizes the standard axes in :data:`VARIATIONS` directly, and — since the
    client now takes free-text variations — any custom sub-folder that is not a
    run folder yet holds eval runs. That way a campaign run entirely under
    hand-named buckets like ``test`` / ``test1`` still rolls up at the model
    level (same rule :func:`scan_variations` uses to surface them).
    """
    try:
        names = os.listdir(path)
    except OSError:
        return False
    for name in names:
        sub = os.path.join(path, name)
        if not os.path.isdir(sub):
            continue
        if name in VARIATIONS:
            return True
        if parse_run_name(name):      # a run folder, not a variation bucket
            continue
        try:
            if any(parse_run_name(child)
                   and os.path.isdir(os.path.join(sub, child))
                   for child in os.listdir(sub)):
                return True
        except OSError:
            pass
    return False


def scan_variations(model_dir: str, only=None) -> dict:
    """``{variation: [episodes]}`` for one ``<model_stem>/``.

    Every name in :data:`VARIATIONS` is present even when it has no episodes
    yet — "not run yet" is the useful thing to see mid-campaign. Runs sitting
    directly under *model_dir* (the pre-split layout) group under
    :data:`NO_VARIATION` so old logs still appear.

    *only*: if given (e.g. :data:`CORE_VARIATIONS`), restrict to that exact
    ordered list of folder names — no extras, no ``*_test`` siblings, no
    pre-split direct runs. Empty folders still appear as "not run yet".
    """
    if only is not None:
        names = tuple(only)
        return {v: scan_episodes(os.path.join(model_dir, v)) for v in names}

    groups = {v: scan_episodes(os.path.join(model_dir, v)) for v in VARIATIONS}
    # Any other sub-folder that holds runs: a hand-made bucket, or a variation
    # renamed since. Surfaced rather than silently dropped.
    try:
        for name in sorted(os.listdir(model_dir)):
            sub = os.path.join(model_dir, name)
            if (name not in VARIATIONS and os.path.isdir(sub)
                    and not parse_run_name(name)):
                extra = scan_episodes(sub)
                if extra:
                    groups[name] = extra
    except OSError:
        pass
    direct = scan_episodes(model_dir)
    if direct:
        groups[NO_VARIATION] = direct
    return groups


def format_rollup(model_dir: str, groups: dict = None,
                  checkpoint: str = "") -> str:
    """Per-variation comparison table — the campaign's headline artifact."""
    if groups is None:
        groups = scan_variations(model_dir)
    all_eps = [e for eps in groups.values() for e in eps]
    ckpt = checkpoint or next((e["checkpoint"] for e in reversed(all_eps)
                               if e["checkpoint"]), "")

    out = ["=" * 78, "Real-robot eval — success rate by variation", "=" * 78]
    if ckpt:
        out.append(f"checkpoint : {ckpt}")
    out.append(f"model dir  : {model_dir}")
    out.append(f"generated  : {datetime.datetime.now().strftime(_META_TIME_FMT)}")
    out += ["", " rate     n   succ  fail  other  variation"]

    width = max([len(n) for n in groups] + [11])
    for name, eps in groups.items():
        st = tally(eps)
        other = st["aborted"] + st["unfinished"]
        note = "  (not run yet)" if not eps else ""
        out.append((f"{_pct(st['success_rate'])} {st['scored']:4d}  "
                    f"{st['success']:4d}  {st['fail']:4d}  {other:5d}  "
                    f"{name:<{width}}{note}").rstrip())

    total = tally(all_eps)
    out.append("-" * 78)
    out.append(f"{_pct(total['success_rate'])} {total['scored']:4d}  "
               f"{total['success']:4d}  {total['fail']:4d}  "
               f"{total['aborted'] + total['unfinished']:5d}  TOTAL")
    out.append("")

    # Which episode numbers landed where, per variation. Numbering restarts in
    # each variation, so "ep003" is only meaningful next to its variation name.
    for name, eps in groups.items():
        if not eps:
            continue
        out.append(f"-- {name} " + "-" * max(0, 74 - len(name)))
        by_result = {}
        for e in eps:
            by_result.setdefault(e["result"] or "unfinished", []).append(e)
        for key in ("success", "fail", "aborted", "unfinished"):
            if key in by_result:
                out.append(textwrap.fill(
                    f"{key:<10} ({len(by_result[key]):2d}): "
                    + ", ".join(_ep_tag(e) for e in by_result[key]),
                    width=78, subsequent_indent=" " * 17))
    out.append("=" * 78)
    return "\n".join(out)


def write_rollup(model_dir: str, groups: dict = None,
                 checkpoint: str = "",
                 filename: str = ROLLUP_TXT) -> dict:
    """Write a variation roll-up at the model level. Returns the totals.

    *filename* defaults to :data:`ROLLUP_TXT` (``summary_by_variation.txt``);
    core-only tallies write :data:`CORE_ROLLUP_TXT` so they never overwrite the
    full campaign roll-up that the live eval server keeps updating.
    """
    if groups is None:
        groups = scan_variations(model_dir)
    with open(os.path.join(model_dir, filename), "w") as f:
        f.write(format_rollup(model_dir, groups, checkpoint) + "\n")
    return tally([e for eps in groups.values() for e in eps])


def group_by_instruction(groups: dict, variations=None) -> dict:
    """``{instruction: {variation: [episodes]}}`` from a variation→episodes map.

    *variations* seeds every instruction's inner dict (empty list when that
    axis has no runs for the task), so the write-up always shows all four
    secondary headings even when a task was only run on some axes.
    """
    axes = tuple(variations) if variations is not None else tuple(groups)
    by_instr = {}
    for var, eps in groups.items():
        for e in eps:
            instr = e["instruction"] or "(no instruction)"
            bucket = by_instr.setdefault(instr, {v: [] for v in axes})
            if var not in bucket:
                bucket[var] = []
            bucket[var].append(e)
    # Stable-ish order: first-seen instruction across the axis scan order,
    # then alphabetical for anything else. Prefer the order episodes actually
    # appeared in the first variation that has them.
    return by_instr


def format_core_by_task(model_dir: str, groups: dict = None,
                       checkpoint: str = "",
                       variations=None) -> str:
    """Task-first write-up: instruction → Basic/Distractor/Background/height/lighting.

    Each secondary line is ``success / scored`` for that (task, variation)
    cell. Unfinished / aborted runs are excluded from the denominator (same
    rule as :func:`tally`).
    """
    axes = tuple(variations) if variations is not None else CORE_VARIATIONS
    if groups is None:
        groups = scan_variations(model_dir, only=axes)

    all_eps = [e for eps in groups.values() for e in eps]
    ckpt = checkpoint or next((e["checkpoint"] for e in reversed(all_eps)
                               if e["checkpoint"]), "")
    by_instr = group_by_instruction(groups, variations=axes)

    # Order tasks by earliest stamp across any axis (campaign chronology),
    # falling back to the instruction string.
    def _task_key(instr):
        stamps = [e["stamp"] for eps in by_instr[instr].values() for e in eps]
        return (min(stamps) if stamps else "9999_999999", instr)

    out = ["=" * 78, "Real-robot eval — success / total by task × variation",
           "=" * 78]
    if ckpt:
        out.append(f"checkpoint : {ckpt}")
    out.append(f"model dir  : {model_dir}")
    out.append(f"generated  : {datetime.datetime.now().strftime(_META_TIME_FMT)}")
    out.append(f"variations : {', '.join(CORE_LABELS.get(v, v) for v in axes)}")
    out.append("")

    if not by_instr:
        out += ["no eval runs found yet.", "=" * 78]
        return "\n".join(out)

    for instr in sorted(by_instr, key=_task_key):
        out.append("# " + instr)
        for var in axes:
            eps = by_instr[instr].get(var, [])
            st = tally(eps)
            label = CORE_LABELS.get(var, var)
            if st["scored"] == 0 and st["total"] == 0:
                cell = "  - / -     (not run)"
            elif st["scored"] == 0:
                cell = (f"  0 / 0     "
                        f"(+{st['aborted'] + st['unfinished']} not scored)")
            else:
                extra = ""
                other = st["aborted"] + st["unfinished"]
                if other:
                    extra = f"   (+{other} not scored)"
                cell = (f"  {st['success']} / {st['scored']}"
                        f"   ({_pct(st['success_rate']).strip()}){extra}")
            out.append(f"## {label}")
            out.append(cell)
        out.append("")

    # Axis totals + grand total for a one-glance footer.
    out.append("-" * 78)
    out.append("# TOTAL")
    for var in axes:
        st = tally(groups.get(var, []))
        label = CORE_LABELS.get(var, var)
        out.append(f"## {label}")
        out.append(f"  {st['success']} / {st['scored']}"
                   f"   ({_pct(st['success_rate']).strip()})")
    grand = tally(all_eps)
    out.append("## ALL")
    out.append(f"  {grand['success']} / {grand['scored']}"
               f"   ({_pct(grand['success_rate']).strip()})")
    out.append("=" * 78)
    return "\n".join(out)


def write_core_by_task(model_dir: str, groups: dict = None,
                      checkpoint: str = "",
                      variations=None,
                      filename: str = CORE_ROLLUP_TXT) -> dict:
    """Write :data:`CORE_ROLLUP_TXT`. Returns the grand-total :func:`tally`."""
    axes = tuple(variations) if variations is not None else CORE_VARIATIONS
    if groups is None:
        groups = scan_variations(model_dir, only=axes)
    with open(os.path.join(model_dir, filename), "w") as f:
        f.write(format_core_by_task(model_dir, groups, checkpoint,
                                    variations=axes) + "\n")
    return tally([e for eps in groups.values() for e in eps])


def one_line(stats: dict) -> str:
    """Compact tally for a terminal, e.g. ``7 episodes: 5 success / 2 fail (71.4%)``."""
    line = (f"{stats['scored']} episodes: {stats['success']} success / "
            f"{stats['fail']} fail ({_pct(stats['success_rate']).strip()})")
    extra = []
    if stats["aborted"]:
        extra.append(f"{stats['aborted']} aborted")
    if stats["unfinished"]:
        extra.append(f"{stats['unfinished']} unfinished")
    return line + (f"  [+{', '.join(extra)}, not counted]" if extra else "")


# CLI
def _resolve_axes(args):
    """Variation folders for the default task-first tally, or None for --full."""
    if getattr(args, "full", False):
        if args.only:
            raise SystemExit("use --full or --only, not both")
        return None
    if args.only:
        names = tuple(n.strip() for n in args.only.split(",") if n.strip())
        if not names:
            raise SystemExit("--only needs at least one variation name")
        for n in names:
            validate_variation(n)
        return names
    return CORE_VARIATIONS


def _find_model_dirs(path: str):
    """``path`` itself if it is a model dir, else its immediate children that are.

    Also accepts a variation sub-folder (``…/model_360/basic``): walks up one
    level so the default task-first tally still runs on the whole campaign.
    """
    if is_model_dir(path):
        return [path]
    parent = os.path.dirname(os.path.abspath(path.rstrip(os.sep)))
    if parent and is_model_dir(parent):
        return [parent]
    try:
        kids = [os.path.join(path, n) for n in sorted(os.listdir(path))]
    except OSError:
        return []
    return [d for d in kids if os.path.isdir(d) and is_model_dir(d)]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="Tally real-robot eval episodes (success / fail per run). "
                    "Default: task × Basic/Distractor/Background/height/lighting.")
    ap.add_argument("path", help="an eval/<model_stem>/ dir, or any dir above it")
    ap.add_argument("--print-only", action="store_true",
                    help="print the summary without rewriting output files")
    ap.add_argument("--full", action="store_true",
                    help="legacy full scan: every variation folder (incl. *_test), "
                         f"regenerate summary.txt / episodes.csv / {ROLLUP_TXT}")
    ap.add_argument("--only", metavar="NAMES",
                    help="comma-separated exact variation folder names for the "
                         f"task-first tally (default: {','.join(CORE_VARIATIONS)}); "
                         f"writes {CORE_ROLLUP_TXT}")
    # Kept so old one-liners with --core keep working; default is already core.
    ap.add_argument("--core", action="store_true",
                    help=argparse.SUPPRESS)
    args = ap.parse_args(argv)

    if not os.path.isdir(args.path):
        print(f"not a directory: {args.path}", file=sys.stderr)
        return 1

    only = _resolve_axes(args)

    # ---- default / --only: task-first over exact folder names ---------------
    if only is not None:
        model_dirs = _find_model_dirs(args.path)
        if not model_dirs:
            if any(os.path.isdir(os.path.join(args.path, v)) for v in only):
                model_dirs = [args.path]
        if not model_dirs:
            print(f"no model dir with {', '.join(only)} under {args.path}",
                  file=sys.stderr)
            return 1

        for model_dir in model_dirs:
            groups = scan_variations(model_dir, only=only)
            print(format_core_by_task(model_dir, groups, variations=only))
            if not args.print_only:
                write_core_by_task(model_dir, groups, variations=only)
                print(f"wrote {os.path.join(model_dir, CORE_ROLLUP_TXT)}\n")
        return 0

    # ---- --full: regenerate every per-variation summary + classic roll-up ---
    roots = find_roots(args.path)
    model_dirs = sorted(
        {d for d in [args.path] + [os.path.dirname(r) for r in roots]
         if is_model_dir(d)})
    if not roots and not model_dirs:
        print(f"no eval runs found under {args.path}", file=sys.stderr)
        return 1

    for root in roots:
        episodes = scan_episodes(root)
        print(format_summary(episodes, root=root))
        if not args.print_only:
            write_summary(root, episodes)
            print(f"wrote {os.path.join(root, SUMMARY_TXT)} and "
                  f"{os.path.join(root, EPISODES_CSV)}\n")

    for model_dir in model_dirs:
        print(format_rollup(model_dir))
        if not args.print_only:
            write_rollup(model_dir)
            print(f"wrote {os.path.join(model_dir, ROLLUP_TXT)}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
